    /// <summary>
    /// Packs signed 16-bit client coordinates (x, y) into a Win32 lParam.
    /// </summary>
    public static nint MakeLParam(int x, int y)
    {
        return (nint)(((short)y << 16) | ((ushort)x & 0xFFFF));
    }

    public static int GetXLParam(nint lParam) => (short)((long)lParam & 0xFFFF);
    public static int GetYLParam(nint lParam) => (short)(((long)lParam >> 16) & 0xFFFF);

    public static string GetWindowTitle(IntPtr hWnd)
    {
        if (hWnd == IntPtr.Zero) return string.Empty;
        var sb = new StringBuilder(512);
        int len = GetWindowTextW(hWnd, sb, sb.Capacity);
        return len > 0 ? sb.ToString(0, len) : string.Empty;
    }

    public static string GetWindowClassName(IntPtr hWnd)
    {
        if (hWnd == IntPtr.Zero) return string.Empty;
        var sb = new StringBuilder(256);
        int len = GetClassNameW(hWnd, sb, sb.Capacity);
        return len > 0 ? sb.ToString(0, len) : string.Empty;
    }
